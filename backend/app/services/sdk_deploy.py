"""Deploying Flow Designer flows with the ServiceNow SDK (Fluent) into a scoped application.

A flow can't be written through the Table API (it is spread across sys_hub_* tables plus a compiled
snapshot), so nowBuilder writes the flow as Fluent source into a ServiceNow SDK project, runs
`now-sdk build` and `now-sdk install` against the connected instance, and reads the flow back.

**Nothing to set up by hand.** With Node.js 20+ on the backend host, the first flow deployment:

1. stores a credential for the connected instance in nowBuilder's own SDK credential folder
   (`now-sdk auth --add <url> --type basic --alias <alias> --username <user> --password-stdin`; the
   password goes through stdin, never the command line or logs; `SN_SDK_CREDENTIALS_DIR` keeps it
   apart from any credentials you created yourself),
2. creates a scoped SDK application for that instance in `<data_dir>/sdk/<instance host>/`
   (`now-sdk init`, scope `x_<company code>_nbuild`, falling back to writing the project files
   itself), and runs `npm install`,
3. then for every flow: writes `src/fluent/nowbuilder_<name>.now.ts`, `now-sdk build`,
   `now-sdk install --auth <alias>` (flows are activated unless NOWBUILDER_SDK_ACTIVATE_FLOWS=false).

Settings (backend/.env, all optional):

    NOWBUILDER_SDK_AUTO_SETUP      true (default): create and manage the SDK project automatically
    NOWBUILDER_SDK_PROJECT_DIR     use your own SDK project (made with `now-sdk init`) instead
    NOWBUILDER_SDK_SCOPE           the scope to create / require (x_...)
    NOWBUILDER_SDK_VERSION         @servicenow/sdk version (default 4.14.0, what flow_catalog.json was read from)
    NOWBUILDER_SDK_AUTH_ALIAS      use an existing `now-sdk auth` alias instead of the instance sign-in
    NOWBUILDER_SDK_INSTANCE_URL    optional safety pin: when set, only install into this instance. Leave it
                                   empty (default) and flows install into whichever instance is connected
    NOWBUILDER_SDK_ACTIVATE_FLOWS  true (default) / false

Never accepts user-supplied commands, file paths or aliases. A plan built in Global installs its flows into
a Global application ("nowBuilder Global", `<project>/global/`, sharing the scoped project's SDK install);
if the instance or SDK can't take a Global application, the flow goes into the scoped app and says so.
"""
