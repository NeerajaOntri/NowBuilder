def _slug(generated: dict) -> str:
    record = generated.get("record") or {}
    slug = re.sub(r"[^a-z0-9_]", "_", str(record.get("name", "")).lower()).strip("_")[:54]
    slug = re.sub(r"_+", "_", slug)
    if not _ID.fullmatch(slug):
        raise SDKDeployError("Invalid flow identifier: give the flow a name that starts with a letter.")
    return slug


def _ours(text: str) -> bool:
    return text.startswith((GENERATED_MARK, *LEGACY_GENERATED_MARKS))


def check_target(instance_url: str) -> None:
    pinned = _env("NOWBUILDER_SDK_INSTANCE_URL").rstrip("/").lower()
    if pinned and pinned != instance_url.rstrip("/").lower():
        raise SDKDeployError(f"SDK installs are pinned to {pinned} (NOWBUILDER_SDK_INSTANCE_URL), "
                             f"not {instance_url}.")


GLOBAL_DIR = "global"
GLOBAL_APP_DIR = "global_app"                 # the Global application project, inside the scoped one (shares its node_modules)
GLOBAL_APP_NAME = "nowBuilder Global"
OUR_GLOBAL_APP_NAMES = ("nowBuilder Global", "Now" + " Builder Global")
GLOBAL_UNSUPPORTED = ".global-unsupported"


def _local_sdk(project: Path) -> list[str]:
    """now-sdk from the project's own node_modules (works from a sub-project too)."""
    exe = project / "node_modules" / ".bin" / ("now-sdk.cmd" if os.name == "nt" else "now-sdk")
    return [str(exe)] if exe.is_file() else [_bin("npx"), "--no-install", "now-sdk"]


GLOBAL_CONFIG = {"scope": "global", "scopeId": "global", "packageResolverVersion": "2.0.0"}


def global_project(project: Path) -> Path:
    """A Global project next to the scoped one: same SDK install, its own now.config.json.

    now.config.json reference (SDK 4.14): `scope` and `scopeId` may both be "global", and Global apps
    need `packageResolverVersion` "2.0.0". Records then land in the Global scope itself, so Flow
    Designer shows the flow under Global. Supported on instances from the Australia release."""
    root = project / GLOBAL_DIR
    config = root / "now.config.json"
    if config.is_file():                       # an earlier nowBuilder wrote a Global *application* id here
        try:
            current = json.loads(config.read_text(encoding="utf-8"))
        except ValueError:
            current = {}
        if current.get("scopeId") != "global" and str(current.get("name") or "").endswith(" Global"):
            app_root = project / GLOBAL_APP_DIR      # that was the Global application: keep its id there
            if not (app_root / "now.config.json").is_file():
                (app_root / "src" / "fluent").mkdir(parents=True, exist_ok=True)
                (app_root / "now.config.json").write_text(json.dumps({**current, "name": GLOBAL_APP_NAME}, indent=2)
                                                          + "\n", encoding="utf-8")
            config.write_text(json.dumps({**GLOBAL_CONFIG, "name": GLOBAL_APP_NAME}, indent=2) + "\n", encoding="utf-8")
            (root / GLOBAL_UNSUPPORTED).unlink(missing_ok=True)
    if not config.is_file():
        (root / "src" / "fluent").mkdir(parents=True, exist_ok=True)
        (root / "package.json").write_text(json.dumps({
            "name": PACKAGE_NAME + "-global", "version": "1.0.0", "private": True,
            "description": "Flows deployed by nowBuilder into Global",
            "devDependencies": {"@servicenow/sdk": _sdk_version()},
        }, indent=2) + "\n", encoding="utf-8")
        config.write_text(json.dumps({**GLOBAL_CONFIG, "name": GLOBAL_APP_NAME}, indent=2) + "\n", encoding="utf-8")
    return root


def global_app_project(project: Path, client=None) -> Path:
    """nowBuilder's Global *application* ("nowBuilder Global": a sys_app whose scope is global), reusing
    the one already on the instance so redeploys update it rather than creating another."""
    root = project / GLOBAL_APP_DIR
    config = root / "now.config.json"
    if config.is_file() and not (root / "package.json").is_file():
        (root / "package.json").write_text(json.dumps({
            "name": PACKAGE_NAME + "-global-app", "version": "1.0.0", "private": True,
            "devDependencies": {"@servicenow/sdk": _sdk_version()}}, indent=2) + "\n", encoding="utf-8")
    if not config.is_file():
        app_id = ""
        if client is not None:
            try:
                names = ",".join(OUR_GLOBAL_APP_NAMES)
                rows = client.query("sys_scope", f"scope=global^nameIN{names}", ["sys_id"], limit=1)
                app_id = str((rows[0] if rows else {}).get("sys_id") or "")
            except Exception:  # noqa: BLE001 - unreadable: a new application
                app_id = ""
        (root / "src" / "fluent").mkdir(parents=True, exist_ok=True)
        (root / "package.json").write_text(json.dumps({
            "name": PACKAGE_NAME + "-global-app", "version": "1.0.0", "private": True,
            "description": "Flows deployed by nowBuilder into its Global application",
            "devDependencies": {"@servicenow/sdk": _sdk_version()},
        }, indent=2) + "\n", encoding="utf-8")
        config.write_text(json.dumps({"scope": "global", "scopeId": app_id if re.fullmatch(r"[0-9a-f]{32}", app_id)
                                      else uuid.uuid4().hex, "name": GLOBAL_APP_NAME}, indent=2) + "\n",
                          encoding="utf-8")
    return root


RELEASES_BEFORE_AUSTRALIA = ("vancouver", "washington", "xanadu", "yokohama", "zurich")


def older_release(release: str) -> str:
    """The release name when the instance is known to be older than Australia (Global SDK installs)."""
    low = str(release or "").lower()
    for name in RELEASES_BEFORE_AUSTRALIA:
        if name in low:
            return name.capitalize()
    return ""


def _reason(exc: Exception) -> str:
    """The lines of an SDK failure that say why, not the banner it starts with."""
    lines = [ln.strip() for ln in str(exc).splitlines() if ln.strip()]
    useful = [ln for ln in lines if re.search(r"(?i)error|fail|not supported|denied|invalid|unable|cannot|can't", ln)
              and not ln.startswith("[now-sdk] Starting")]
    text = " ".join((useful or lines)[-2:])
    text = re.sub(r"See execution details at \S+", "", text).strip()
    text = re.sub(r"`[^`]*--auth [^`]*`", "now-sdk install", text)[:300]
    return text or "the SDK refused it"


def global_unsupported(project: Path) -> str:
    mark = project / GLOBAL_UNSUPPORTED
    return mark.read_text(encoding="utf-8").strip() if mark.is_file() else ""


def _write_flow(app_dir: Path, slug: str, source: str) -> Path:
    fluent = app_dir / "src" / "fluent"
    fluent.mkdir(parents=True, exist_ok=True)
    target = fluent / f"nowbuilder_{slug}.now.ts"
    if target.is_symlink():
        raise SDKDeployError("Refusing to write to a symlink.")
    # A flow deployed before the rename lives under the old file name with the same Now.ID values;
    # keeping both files would define the flow twice, so the old one (ours) is replaced.
    for prefix in LEGACY_FILE_PREFIXES:
        old = fluent / f"{prefix}{slug}.now.ts"
        if old.is_file() and not old.is_symlink() and _ours(old.read_text(encoding="utf-8")):
            old.unlink()
    if target.exists():
        existing = target.read_text(encoding="utf-8")
        if existing != source and not _ours(existing):
            raise SDKDeployError(f"{target.name} already exists and wasn't written by nowBuilder. Rename the flow "
                                 "or resolve it in the SDK project.")
    target.write_text(source, encoding="utf-8")
    return target


def _attempt(app_dir: Path, sdk: list[str], slug: str, source: str, plain: str, **kw) -> dict:
    """Build (and install) the flow. If the SDK refuses the inline script that carries record values in a
    static-only input (Send Email's body), try once more with that input as fixed text and say so."""
    target = _write_flow(app_dir, slug, source)
    try:
        return _build_install(app_dir, sdk, target, **kw)
    except SDKDeployError as exc:
        if not plain:
            raise
        first = str(exc).strip().splitlines()[0][:300] if str(exc).strip() else "refused"
        target = _write_flow(app_dir, slug, plain)
        result = _build_install(app_dir, sdk, target, **kw)
        return {**result, "body_note": ("The email body went in with [placeholders]: this SDK refused the record "
                                        f"values written as pill references ({first}). Drag those pills into the "
                                        "body in Flow Designer, or ask for a notification instead.")}


def _build_install(app_dir: Path, sdk: list[str], target: Path, *, install: bool, alias: str,
                   env: dict, on_status) -> dict:
    on_status("Building the flow with the ServiceNow SDK")
    build_output = _execute(app_dir, [*sdk, "build"], 600)
    result = {"status": "built", "project_dir": str(app_dir), "source_file": str(target.relative_to(app_dir)),
              "build_output": build_output, "installed": False}
    if not install:
        return result
    if not alias:
        raise SDKDeployError("No sign-in for the SDK install: connect the instance with a username and password, "
                             "or set NOWBUILDER_SDK_AUTH_ALIAS.")
    command = [*sdk, "install", "--auth", alias]
    if not _activate():
        command += ["--skip-flow-activation", "true"]
    on_status("Installing the flow into the instance (now-sdk install)")
    install_output = _execute(app_dir, command, 900, env)
    result.update(status="installed", installed=True, install_output=install_output, activated=_activate())
    return result


def run_scoped_flow(generated: dict, *, install: bool = False, instance_url: str | None = None,
                    username: str | None = None, password: str | None = None, client=None,
                    on_status=lambda s: None, application: str = "scoped", release: str = "") -> dict:
    """Write the flow's Fluent source into an SDK project, build it, and optionally install it.

    `application` "global" installs it into nowBuilder's Global application (the plan is built in
    Global); if the SDK or the instance can't do that, it goes into nowBuilder's scoped app and the
    result says why (`application_note`). Serialized per process: the projects and credentials are shared."""
    try:
        mode = "placeholders" if (_env("NOWBUILDER_FLOW_BODY_PILLS") or "").lower() == "placeholders" else "references"
        source = generate_flow_source(generated, static_pills=mode) if mode != "references" else generate_flow_source(generated)
        # If this SDK refuses pill references in a static-only input, the fallback has [placeholders].
        plain = generate_flow_source(generated, static_pills="placeholders") if has_static_pills(generated) else ""
        if plain == source:
            plain = ""
    except UnsupportedFlow as exc:
        raise SDKDeployError(f"Flow not supported by SDK exporter: {exc}") from exc
    slug = _slug(generated)
    if instance_url:
        check_target(instance_url)
    load_dotenv()
    own_project = bool(_env("NOWBUILDER_SDK_PROJECT_DIR"))
    if instance_url and not own_project:
        _wait_for_setup(instance_url, username or "", password or "", client, on_status)
    if not _LOCK.acquire(blocking=False):
        raise SDKDeployError("Another SDK build/install is already running. Try again in a minute.")
    try:
        if instance_url:
            project, alias = ensure_project(instance_url, username or "", password or "", client, on_status)
        else:
            project, alias = _settings()
        env = _cred_env() if instance_url and username and password else {}
        notes: list[str] = []
        if application == "global" and not own_project:
            # 1. Global itself (scopeId "global"); 2. nowBuilder's Global application (a sys_app in the
            # global scope, which older releases accept); 3. the scoped app - each refusal is reported.
            older = older_release(release)
            for app_dir, label in ((global_project(project), "Global"),
                                   (global_app_project(project, client), GLOBAL_APP_NAME)):
                why = global_unsupported(app_dir)
                if label == "Global" and older and not why:
                    why = f"this instance runs the {older} release, and installing straight into Global needs Australia or later"
                if not why:
                    try:
                        on_status(f"Installing into {label}")
                        result = _attempt(app_dir, _local_sdk(project), slug, source, plain, install=install,
                                          alias=alias, env=env, on_status=on_status)
                        if notes:
                            notes.append(f"It is in {label}, an application in the Global scope: its records are "
                                         "Global, and Flow Designer lists it under that application.")
                            result["application_note"] = " ".join(notes)
                        return {**result, "scope": "global", "application": label}
                    except SDKDeployError as exc:
                        why = _reason(exc)
                        (app_dir / "src" / "fluent" / f"nowbuilder_{slug}.now.ts").unlink(missing_ok=True)
                        if install:      # not retried on every deploy; delete the file to try again
                            (app_dir / GLOBAL_UNSUPPORTED).write_text(why + "\n", encoding="utf-8")
                notes.append(f"Not installed straight into {label}: {why}.")
            notes.append("So it was installed in nowBuilder's scoped app.")
        note = " ".join(notes)
        result = _attempt(project, _local_sdk(project), slug, source, plain, install=install, alias=alias, env=env,
                          on_status=on_status)
        scope = json.loads((project / "now.config.json").read_text(encoding="utf-8")).get("scope", "scoped")
        return {**result, "scope": scope, "application": scope, **({"application_note": note} if note else {})}
    finally:
        _LOCK.release()


def read_back_flow(client, name: str) -> dict | None:
    """The installed flow as the instance reports it: sys_id, active, status."""
    rows = client.query("sys_hub_flow", f"name={name}^type=flow^ORDERBYDESCsys_updated_on",
                        ["sys_id", "name", "active", "status", "sys_scope"], limit=1)
    if not rows:
        return None
    row = rows[0]
    scope = row.get("sys_scope")
    scope = str((scope.get("value") if isinstance(scope, dict) else scope) or "")
    return {"sys_id": row.get("sys_id"), "active": str(row.get("active")) == "true",
            "status": row.get("status"), "sys_scope": scope,
            "url": f"{client.url}/$flow-designer.do#/flow-designer/{row.get('sys_id')}"}


def older_copies(client, name: str, keep_sys_id: str) -> list[dict]:
    """Active flows with the same name in nowBuilder's scoped apps: an earlier install of this flow that
    would send everything twice next to the new one."""
    try:
        rows = client.query("sys_hub_flow", f"name={name}^type=flow^active=true^sys_id!={keep_sys_id}",
                            ["sys_id", "sys_scope"], limit=10)
    except Exception:  # noqa: BLE001 — unreadable: nothing to report
        return []
    out = []
    for r in rows:
        scope_id = r.get("sys_scope")
        scope_id = str((scope_id.get("value") if isinstance(scope_id, dict) else scope_id) or "")
        try:
            scope = client.get("sys_scope", scope_id, fields=["scope", "name"]) \
                if scope_id and scope_id != "global" else None
        except Exception:  # noqa: BLE001
            scope = None
        if not scope:
            continue
        if re.fullmatch(r"x_[a-z0-9]+_nbuild\d*", str(scope.get("scope") or "")) or \
                str(scope.get("name") or "") in OUR_GLOBAL_APP_NAMES:
            out.append({"sys_id": r.get("sys_id"), "scope": scope.get("name") or scope.get("scope")})
    return out
