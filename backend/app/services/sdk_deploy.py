LEGACY_FILE_PREFIXES = (f"{_OLD}_",)
LEGACY_PACKAGE_NAMES = (f"{_OLD}-automation",)
# Packages the SDK loads at runtime that npm has been seen to leave out; pinned so they're always there.
SAFETY_DEPS = {"lodash": "^4.17.21"}
_MISSING_MODULE = re.compile(r"Cannot find (?:module|package) '((?:@[\w.-]+/)?[\w.-]+)")


class SDKDeployError(Exception):
    pass


class SDKSetupPending(SDKDeployError):
    """The one-time SDK setup is still running in the background; deploy again when it's done."""


# ---------- settings ----------

def _env(name: str, default: str = "") -> str:
    return os.getenv(name, default).strip()


def _sdk_version() -> str:
    return _env("NOWBUILDER_SDK_VERSION") or DEFAULT_SDK_VERSION


def _auto() -> bool:
    return _env("NOWBUILDER_SDK_AUTO_SETUP", "true").lower() not in ("false", "0", "no")


def _activate() -> bool:
    return _env("NOWBUILDER_SDK_ACTIVATE_FLOWS", "true").lower() not in ("false", "0", "no")


def _data_root() -> Path:
    from ..config import get_settings
    return (Path(get_settings().data_dir).expanduser().resolve()) / "sdk"


def _bin(name: str) -> str:
    """npx / npm / node, with the .cmd shims Windows needs."""
    return shutil.which(f"{name}.cmd" if os.name == "nt" and name != "node" else name) or name


def node_version() -> str | None:
    try:
        out = subprocess.run([_bin("node"), "--version"], capture_output=True, text=True, timeout=20, check=False)
    except (OSError, subprocess.SubprocessError):
        return None
    return (out.stdout.strip() or None) if out.returncode == 0 else None


def configured() -> bool:
    """Whether flows can be deployed at all: your own SDK project, or automatic setup with Node.js."""
    load_dotenv()
    if _env("NOWBUILDER_SDK_PROJECT_DIR"):
        return True
    return _auto() and node_version() is not None


def why_not_configured() -> str:
    load_dotenv()
    if not _auto():
        return ("Flow deployment is off: set NOWBUILDER_SDK_AUTO_SETUP=true (or NOWBUILDER_SDK_PROJECT_DIR) "
                "in backend/.env and restart the backend.")
    return ("Node.js isn't installed on the machine running the backend, so the ServiceNow SDK can't run. "
            "Install Node.js 20 or later (nodejs.org, LTS), restart the backend, and deploy again.")


# ---------- running commands ----------

def _redact(text: str) -> str:
    return re.sub(r"(?i)(password|pwd|token|secret)\s*[:=]\s*\S+", r"\1=[REDACTED]", text)


def _tail(path: Path, lines: int = 30) -> str:
    try:
        return _redact("\n".join(path.read_text(encoding="utf-8", errors="replace").splitlines()[-lines:]))
    except OSError:
        return ""


def _execute(cwd: Path, command: list[str], timeout: int, env: dict | None = None,
             stdin: str | None = None, log: Path | None = None, live: bool = False) -> str:
    """Run one SDK / npm command. `log`: append its output to a file (so a slow step can be watched);
    `live`: let it print straight to the console (the setup command). stdin is closed unless given,
    so a command that unexpectedly asks a question fails instead of hanging."""
    label = " ".join(command[1:4])
    full_env = {**os.environ, **(env or {})}
    stdin_kw = {"input": stdin} if stdin is not None else {"stdin": subprocess.DEVNULL}
    try:
        if live:
            print(f"\n$ {' '.join(command[:1] + command[1:])}".replace(stdin or "\0", "***"), flush=True)
            result = subprocess.run(command, cwd=cwd, shell=False, text=True, timeout=timeout, check=False,
                                    env=full_env, **stdin_kw)
            output = ""
        elif log is not None:
            log.parent.mkdir(parents=True, exist_ok=True)
            with open(log, "a", encoding="utf-8", errors="replace") as fh:
                fh.write(f"\n$ {label}\n")
                fh.flush()
                result = subprocess.run(command, cwd=cwd, shell=False, text=True, timeout=timeout, check=False,
                                        env=full_env, stdout=fh, stderr=subprocess.STDOUT, **stdin_kw)
            output = _tail(log)
        else:
            result = subprocess.run(command, cwd=cwd, shell=False, capture_output=True, text=True, encoding="utf-8",
                                    errors="replace", timeout=timeout, check=False, env=full_env, **stdin_kw)
            output = _redact(((result.stdout or "") + "\n" + (result.stderr or ""))[-6000:])
    except FileNotFoundError as exc:
        raise SDKDeployError("Node.js / npm isn't installed on the backend host. Install Node.js 20+ (nodejs.org) "
                             "and restart the backend.") from exc
    except subprocess.TimeoutExpired as exc:
        where = f" Output so far is in {log}." if log else ""
        raise SDKDeployError(f"`{label}` didn't finish in {timeout // 60} minutes.{where} This step downloads from "
                             "npm: check this computer's internet / proxy, then try again.") from exc
    if result.returncode:
        raise SDKDeployError(f"`{label}` failed (exit {result.returncode}): {output.strip()[-3000:]}")
    return output


def _setup_timeout() -> int:
    try:
        return max(300, int(_env("NOWBUILDER_SDK_SETUP_TIMEOUT", "3600")))
    except ValueError:
        return 3600


def _cred_env() -> dict[str, str]:
    path = _data_root() / "credentials"
    path.mkdir(parents=True, exist_ok=True)
    return {"SN_SDK_CREDENTIALS_DIR": str(path)}


def _host_slug(instance_url: str) -> str:
    host = re.sub(r"^https?://", "", instance_url.strip().lower()).split("/")[0]
    return re.sub(r"[^a-z0-9]+", "_", host).strip("_")[:60] or "instance"


def _alias_for(instance_url: str) -> str:
    return ("sf_" + _host_slug(instance_url))[:64]


def store_credential(cwd: Path, instance_url: str, username: str, password: str, local_sdk: bool,
                     log: Path | None = None, live: bool = False) -> str:
    """(Re)create the SDK credential for this instance from the connected sign-in. Returns its alias."""
    alias = _alias_for(instance_url)
    sdk = [_bin("npx"), "--no-install", "now-sdk"] if local_sdk else [_bin("npx"), "--yes", f"@servicenow/sdk@{_sdk_version()}"]
    env = _cred_env()
    try:
        _execute(cwd, [*sdk, "auth", "--delete", alias], 600, env, log=log)
    except SDKDeployError:
        pass  # nothing stored yet
    _execute(cwd, [*sdk, "auth", "--add", instance_url.rstrip("/"), "--type", "basic", "--alias", alias,
                   "--username", username, "--password-stdin"], 600, env, stdin=password + "\n", log=log)
    return alias


# ---------- the SDK project ----------

def _validate(project: Path) -> Path:
    if not project.is_dir() or not (project / "package.json").is_file() or not (project / "now.config.json").is_file():
        raise SDKDeployError("SDK project must be an initialized ServiceNow scoped application (package.json and now.config.json).")
    config = json.loads((project / "now.config.json").read_text(encoding="utf-8"))
    scope = str(config.get("scope") or config.get("scopeName") or config.get("scope_name") or "")
    if not re.fullmatch(r"x_[a-z0-9_]{2,40}", scope):
        raise SDKDeployError("SDK application must be scoped (x_...). Global scope cannot use this deployment bridge.")
    expected_scope = _env("NOWBUILDER_SDK_SCOPE")
    if expected_scope and scope != expected_scope:
        raise SDKDeployError(f"SDK scope mismatch: expected {expected_scope}, project has {scope}. Installation blocked.")
    package = json.loads((project / "package.json").read_text(encoding="utf-8"))
    declared = (package.get("devDependencies") or {}).get("@servicenow/sdk") or \
               (package.get("dependencies") or {}).get("@servicenow/sdk")
    expected = _env("NOWBUILDER_SDK_VERSION")
    if expected and (not declared or declared.lstrip("^~") != expected):
        raise SDKDeployError(f"SDK version mismatch: expected {expected}, project declares {declared!r}.")
    (project / "src" / "fluent").mkdir(parents=True, exist_ok=True)
    return project


def _settings() -> tuple[Path, str]:
    """Your own SDK project (NOWBUILDER_SDK_PROJECT_DIR) and its alias, validated."""
    load_dotenv()
    root = _env("NOWBUILDER_SDK_PROJECT_DIR")
    alias = _env("NOWBUILDER_SDK_AUTH_ALIAS")
    if not root:
        raise SDKDeployError("Configure NOWBUILDER_SDK_PROJECT_DIR, or leave it empty and keep "
                             "NOWBUILDER_SDK_AUTO_SETUP=true so nowBuilder sets the SDK project up itself.")
    if alias and not re.fullmatch(r"[A-Za-z0-9_.-]{1,64}", alias):
        raise SDKDeployError("Invalid SDK authentication alias.")
    try:
        project = Path(root).expanduser().resolve(strict=True)
    except (OSError, RuntimeError) as exc:
        raise SDKDeployError(f"SDK project folder {root} doesn't exist.") from exc
    _validate(project)
    if not (project / "node_modules" / ".bin").is_dir():
        raise SDKDeployError("SDK dependencies missing in the configured project. Run npm install in it.")
    return project, alias


def choose_scope(client) -> str:
    """x_<company code>_nbuild: the instance's vendor prefix, and a name the instance doesn't use yet."""
    wanted = _env("NOWBUILDER_SDK_SCOPE")
    if wanted:
        return wanted
    code = ""
    if client is not None:
        for prop in ("sn_appauthor.all_company_keys", "glide.appcreator.company.code"):
            try:
                rows = client.query("sys_properties", f"name={prop}", ["value"], limit=1)
            except Exception:  # noqa: BLE001 — unreadable property: fall through to the next
                rows = []
            value = str((rows[0].get("value") if rows else "") or "").split(",")[0].strip().lower()
            if re.fullmatch(r"[a-z0-9]{1,10}", value):
                code = value
                break
    if not code:
        raise SDKDeployError("Couldn't read this instance's vendor prefix (system property "
                             "glide.appcreator.company.code). Set NOWBUILDER_SDK_SCOPE=x_<prefix>_nbuild in backend/.env.")
    for suffix in ("nbuild", "nbuild2", "nbuild3", "nbuild4", "nbuild5"):
        scope = f"x_{code}_{suffix}"[:18]
        try:
            taken = client.query("sys_scope", f"scope={scope}", ["sys_id"], limit=1) if client is not None else []
        except Exception:  # noqa: BLE001
            taken = []
        if not taken:
            return scope
    raise SDKDeployError("Every nowBuilder scope name is taken on this instance; set NOWBUILDER_SDK_SCOPE.")


def _write_project(project: Path, scope: str) -> None:
    """The files `now-sdk init` would create for a basic app, when init itself can't run here."""
    project.mkdir(parents=True, exist_ok=True)
    (project / "src" / "fluent").mkdir(parents=True, exist_ok=True)
    (project / "package.json").write_text(json.dumps({
        "name": "nowbuilder-automation", "version": "1.0.0", "private": True,
        "description": "Flows deployed by nowBuilder",
        "scripts": {"build": "now-sdk build", "deploy": "now-sdk install"},
        "devDependencies": {"@servicenow/sdk": _sdk_version(), **SAFETY_DEPS},
    }, indent=2) + "\n", encoding="utf-8")
    (project / "now.config.json").write_text(json.dumps({
        "scope": scope, "scopeId": uuid.uuid4().hex, "name": APP_NAME,
    }, indent=2) + "\n", encoding="utf-8")


def project_dir(instance_url: str) -> Path:
    return _data_root() / _host_slug(instance_url)


def setup_log(instance_url: str) -> Path:
    return _data_root() / f"setup_{_host_slug(instance_url)}.log"


def project_ready(instance_url: str) -> bool:
    project = project_dir(instance_url)
    return (project / "now.config.json").is_file() and any(
        (project / mark).is_file() for mark in (READY_MARK, *LEGACY_READY_MARKS))


LOCK_HEARTBEAT = 30          # seconds between refreshes of a held lock
LOCK_STALE_AFTER = 180       # a lock not refreshed for this long belongs to a setup that died


class _SetupLock:
    """One SDK setup per instance at a time, across processes: the backend's background setup and
    `python -m app.sdk_setup` must never run `npm install` in the same folder together (that is how
    node_modules ends up half-written). The holder refreshes the lock file every LOCK_HEARTBEAT
    seconds; one not refreshed for LOCK_STALE_AFTER seconds was left by a setup that was killed
    (for example a backend restart) and is taken over instead of waited on."""

    def __init__(self, instance_url: str, wait: int, on_status=lambda s: None):
        self.path = _data_root() / f"setup_{_host_slug(instance_url)}.lock"
        self.wait, self.on_status = wait, on_status
        self._stop = threading.Event()

    def __enter__(self):
        import time
        self.path.parent.mkdir(parents=True, exist_ok=True)
        waited = 0
        while True:
            try:
                fd = os.open(self.path, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
                os.write(fd, f"{os.getpid()} {time.time():.0f}".encode())
                os.close(fd)
                threading.Thread(target=self._heartbeat, daemon=True).start()
                return self
            except FileExistsError:
                try:
                    age = time.time() - self.path.stat().st_mtime
                except OSError:
                    continue
                if age > LOCK_STALE_AFTER:
                    self.on_status("Taking over an SDK setup that stopped (its lock wasn't refreshed)")
                    self.path.unlink(missing_ok=True)       # left behind by a setup that was killed
                    continue
                if waited >= self.wait:
                    raise SDKSetupPending("Another ServiceNow SDK setup for this instance is still running. "
                                          "Wait for it to finish, then deploy again.") from None
                if waited % 30 == 0:
                    self.on_status("Waiting for the ServiceNow SDK setup that's already running")
                time.sleep(5)
                waited += 5

    def _heartbeat(self) -> None:
        while not self._stop.wait(LOCK_HEARTBEAT):
            try:
                os.utime(self.path, None)
            except OSError:
                return

    def __exit__(self, *exc):
        self._stop.set()
        self.path.unlink(missing_ok=True)


def _ensure_safety_deps(project: Path) -> None:
    """Older nowBuilder projects were written without SAFETY_DEPS; add them."""
    path = project / "package.json"
    package = json.loads(path.read_text(encoding="utf-8"))
    if package.get("name") not in (PACKAGE_NAME, *LEGACY_PACKAGE_NAMES):
        return                                              # not ours: leave it alone
    dev = package.setdefault("devDependencies", {})
    if all(k in dev for k in SAFETY_DEPS):
        return
    dev.update({k: v for k, v in SAFETY_DEPS.items() if k not in dev})
    path.write_text(json.dumps(package, indent=2) + "\n", encoding="utf-8")


# Packages in the SDK's dependency tree whose install scripts the SDK build needs (the TypeScript
# compiler's native binary, the XML library, the file watcher). npm 11+ skips install scripts until
# they are approved ("npm warn allow-scripts ..."), which leaves `now-sdk build` without them.
SCRIPT_PACKAGES = ("@swc/core", "libxmljs2", "@parcel/watcher")


def _allow_install_scripts(project: Path, log: Path | None, live: bool, on_status) -> None:
    """Approve and run the install scripts npm 11+ skipped. Older npm has no approve-scripts and
    already ran them, so a failure here is ignored."""
    # One package at a time: which ones npm holds back differs per install, and approving a package
    # that isn't waiting makes npm reject the whole command.
    approved = 0
    for package in SCRIPT_PACKAGES:
        try:
            _execute(project, [_bin("npm"), "approve-scripts", package], 600, log=log, live=live)
            approved += 1
        except SDKDeployError:
            continue                    # not installed, not waiting, or npm without approve-scripts
    if not approved:
        return
    on_status("Running the SDK packages' install steps (npm rebuild)")
    _execute(project, [_bin("npm"), "rebuild"], _setup_timeout(), log=log, live=live)


def _sdk_works(project: Path, log: Path | None, live: bool) -> str | None:
    """Run a harmless SDK command; None when the SDK loads, otherwise its error text."""
    try:
        _execute(project, [_bin("npx"), "--no-install", "now-sdk", "auth", "--list"], 300, _cred_env(),
                 log=log, live=live)
        return None
    except SDKDeployError as e:
        return str(e)


def _install_sdk(project: Path, log: Path | None, live: bool, on_status) -> None:
    """npm install, then prove the SDK runs. Repairs what it can: a module the SDK reports missing is
    installed explicitly, otherwise node_modules is deleted and installed again from scratch."""
    timeout = _setup_timeout()
    npm = [_bin("npm"), "install", "--no-audit", "--no-fund", "--include=optional", "--loglevel=http"]
    _ensure_safety_deps(project)
    on_status("Downloading the ServiceNow SDK (npm install, first time only)")
    _execute(project, npm, timeout, log=log, live=live)
    _allow_install_scripts(project, log, live, on_status)
    clean_done = False
    for _ in range(4):
        on_status("Checking the ServiceNow SDK runs")
        error = _sdk_works(project, log, live)
        if error is None:
            (project / READY_MARK).write_text(_sdk_version() + "\n", encoding="utf-8")
            return
        missing = _MISSING_MODULE.search(error)
        name = missing.group(1) if missing else ""
        if name and not name.startswith("."):
            # SDK packages are released together, so a missing @servicenow/* part gets the same version
            spec = f"{name}@{_sdk_version()}" if name.startswith("@servicenow/") else name
            on_status(f"Adding the missing package {spec}")
            _execute(project, [*npm[:2], spec, *npm[2:]], timeout, log=log, live=live)
        elif not clean_done:
            on_status("Reinstalling the ServiceNow SDK from scratch")
            shutil.rmtree(project / "node_modules", ignore_errors=True)
            (project / "package-lock.json").unlink(missing_ok=True)
            _execute(project, npm, timeout, log=log, live=live)
            clean_done = True
        else:
            break
    raise SDKDeployError("The ServiceNow SDK was downloaded but doesn't run on this computer: "
                         f"{(error or '')[-1500:]} Check Node.js is 20 or later (`node -v`), delete "
                         f"{project}, and run `python -m app.sdk_setup` again.")


def ensure_project(instance_url: str, username: str, password: str, client=None, on_status=lambda s: None,
                   live: bool = False, wait: int | None = None) -> tuple[Path, str]:
    """Create (once) the scoped SDK project for this instance, prove the SDK runs, and store the
    instance credential. Slow the first time (npm downloads), so it normally runs in the background
    (`start_setup`) or from the console (`python -m app.sdk_setup`); output goes to `setup_log()`."""
    load_dotenv()
    if _env("NOWBUILDER_SDK_PROJECT_DIR"):
        project, alias = _settings()
        if username and password:
            alias = store_credential(project, instance_url, username, password, local_sdk=True)
        if not alias:
            raise SDKDeployError("No sign-in for the SDK install: connect the instance with a username and password, "
                                 "or set NOWBUILDER_SDK_AUTH_ALIAS.")
        return project, alias
    if not _auto() or node_version() is None:
        raise SDKDeployError(why_not_configured())
    if not (username and password):
        raise SDKDeployError("The ServiceNow SDK needs the instance's username and password: connect the instance "
                             "with 'Username and password' in Settings → ServiceNow instances.")

    _data_root().mkdir(parents=True, exist_ok=True)
    project = project_dir(instance_url)
    log = None if live else setup_log(instance_url)
    if not project_ready(instance_url):
        with _SetupLock(instance_url, _setup_timeout() if wait is None else wait, on_status):
            if not project_ready(instance_url):               # another process may have just finished
                if not (project / "now.config.json").is_file():
                    on_status("Setting up the ServiceNow SDK for this instance (first time only)")
                    scope = choose_scope(client)
                    if project.exists() and any(project.iterdir()):
                        shutil.rmtree(project)                  # a half-made project from a failed attempt
                    project.mkdir(parents=True, exist_ok=True)
                    # The files `now-sdk init` writes for a basic app, written directly: init asks
                    # questions in some versions, and these values are all a flows-only app needs.
                    _write_project(project, scope)
                _validate(project)
                _install_sdk(project, log, live, on_status)
    _validate(project)
    on_status("Signing the ServiceNow SDK in to the instance")
    alias = store_credential(project, instance_url, username, password, local_sdk=True, log=log, live=live)
    return project, alias


# ---------- the one-time setup, in the background ----------

_SETUP: dict[str, dict] = {}
_SETUP_LOCK = threading.Lock()


def setup_state(instance_url: str) -> dict:
    host = _host_slug(instance_url)
    state = dict(_SETUP.get(host) or {})
    if not state:
        state = {"state": "ready" if project_ready(instance_url) else "not started"}
    state["log"] = str(setup_log(instance_url))
    return state


def start_setup(instance_url: str, username: str, password: str, client=None) -> dict:
    """Start the one-time SDK setup for this instance in a background thread (no-op when it is
    ready or already running). Returns the current state."""
    load_dotenv()
    if _env("NOWBUILDER_SDK_PROJECT_DIR") or not configured() or not (username and password):
        return setup_state(instance_url)
    host = _host_slug(instance_url)
    with _SETUP_LOCK:
        if project_ready(instance_url) or (_SETUP.get(host) or {}).get("state") == "running":
            return setup_state(instance_url)
        _SETUP[host] = {"state": "running", "step": "starting"}

    def work() -> None:
        def step(text: str) -> None:
            _SETUP[host]["step"] = text
        try:
            ensure_project(instance_url, username, password, client, on_status=step)
            _SETUP[host] = {"state": "ready"}
        except Exception as exc:  # noqa: BLE001 — reported through setup_state and the next deploy
            _SETUP[host] = {"state": "failed", "error": str(exc)[:2000]}

    threading.Thread(target=work, name=f"sdk-setup-{host}", daemon=True).start()
    return setup_state(instance_url)


def _wait_for_setup(instance_url: str, username: str, password: str, client, on_status) -> None:
    """Make sure the project exists, waiting a few minutes at most so the chat isn't held for long."""
    import time
    state = start_setup(instance_url, username, password, client)
    if state["state"] == "failed":
        _SETUP.pop(_host_slug(instance_url), None)       # the next attempt starts over
        raise SDKDeployError(f"ServiceNow SDK setup failed: {state.get('error')}")
    try:
        wait = max(0, int(_env("NOWBUILDER_SDK_WAIT_SECONDS", "300")))
    except ValueError:
        wait = 300
    waited = 0
    while not project_ready(instance_url):
        state = setup_state(instance_url)
        if state["state"] == "failed":
            _SETUP.pop(_host_slug(instance_url), None)
            raise SDKDeployError(f"ServiceNow SDK setup failed: {state.get('error')}")
        if waited >= wait:
            raise SDKSetupPending(
                "The ServiceNow SDK is still being set up on this computer (first time only: it downloads the "
                f"SDK from npm). Progress: {state['log']}. When it finishes, click Deploy on the plan card again. "
                "To watch it instead, run `python -m app.sdk_setup` in the backend folder.")
        if waited % 30 == 0:
            on_status(f"Setting up the ServiceNow SDK: {state.get('step') or 'working'} ({waited // 60} min)")
        time.sleep(5)
        waited += 5


def sdk_preflight() -> dict:
    """Safe local checks; does not touch the instance."""
    load_dotenv()
    own = _env("NOWBUILDER_SDK_PROJECT_DIR")
    out = {"node": node_version(), "auto_setup": _auto(), "sdk_version": _sdk_version(),
           "activates_flows": _activate(), "instance_url_pinned": _env("NOWBUILDER_SDK_INSTANCE_URL") or None}
    if own:
        project, alias = _settings()
        config = json.loads((project / "now.config.json").read_text(encoding="utf-8"))
        out.update(ready_for_local_build=True, mode="your SDK project", project_dir=str(project), scope=config.get("scope"))
    else:
        root = _data_root()
        projects = sorted(p.parent.name for p in root.glob("*/now.config.json")) if root.exists() else []
        out.update(ready_for_local_build=configured(), mode="automatic", projects=projects,
                   setups={host: dict(v) for host, v in _SETUP.items()},
                   note=None if configured() else why_not_configured())
    return out


