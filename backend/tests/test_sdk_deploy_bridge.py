def test_install_stores_a_credential_from_the_instance_sign_in_and_uses_it(tmp_path, monkeypatch):
    """`now-sdk auth --add ... --password-stdin`: the password goes through stdin, never argv."""
    configured(tmp_path, monkeypatch)
    monkeypatch.setenv('NOWBUILDER_DATA_DIR', str(tmp_path / 'data'))
    from app.config import get_settings
    get_settings.cache_clear()
    monkeypatch.setattr(sdk_deploy, 'generate_flow_source', lambda x, **k: '// Generated by nowBuilder\nsource')
    calls = []
    monkeypatch.setattr(sdk_deploy, '_execute',
                        lambda cwd, cmd, timeout, env=None, stdin=None, **kw: calls.append((cmd, env or {}, stdin)) or 'ok')
    result = sdk_deploy.run_scoped_flow({'record': {'name': 'P1 Escalation'}}, install=True,
                                        instance_url='https://dev410284.service-now.com', username='admin',
                                        password='s3cret')
    get_settings.cache_clear()
    assert result['installed'] and result['activated']
    add = next(c for c in calls if '--add' in c[0])
    assert add[2] == 's3cret\n' and 's3cret' not in ' '.join(add[0])
    assert '--password-stdin' in add[0] and '--username' in add[0] and 'admin' in add[0]
    assert add[1]['SN_SDK_CREDENTIALS_DIR'].endswith('credentials')
    build = next(c for c in calls if c[0][-1] == 'build')
    install = next(c for c in calls if 'install' in c[0] and '--auth' in c[0])
    assert calls.index(build) < calls.index(install)
    assert install[0][install[0].index('--auth') + 1] == 'sf_dev410284_service_now_com'
    assert '--skip-flow-activation' not in install[0]          # flows are activated by default


def _auto_mode(tmp_path, monkeypatch):
    monkeypatch.setattr(sdk_deploy, 'load_dotenv', lambda *a, **k: None)
    monkeypatch.delenv('NOWBUILDER_SDK_PROJECT_DIR', raising=False)
    monkeypatch.setenv('NOWBUILDER_SDK_AUTO_SETUP', 'true')
    monkeypatch.setenv('NOWBUILDER_DATA_DIR', str(tmp_path / 'data'))
    from app.config import get_settings
    get_settings.cache_clear()
    monkeypatch.setattr(sdk_deploy, 'node_version', lambda: 'v22.0.0')
    monkeypatch.setattr(sdk_deploy, 'generate_flow_source', lambda x, **k: '// Generated by nowBuilder\nsrc')
    sdk_deploy._SETUP.clear()


class PrefixClient:
    def query(self, table, query, fields, limit=1):
        if table == 'sys_properties' and 'glide.appcreator.company.code' in query:
            return [{'value': '1234567'}]
        return []


def test_automatic_setup_creates_the_scoped_project_itself(tmp_path, monkeypatch):
    """No SDK project configured: the first flow sets one up for the instance, in the background,
    with its npm output in a log file."""
    _auto_mode(tmp_path, monkeypatch)
    calls = []

    def fake(cwd, cmd, timeout, env=None, stdin=None, log=None, live=False):
        calls.append((cmd, log))
        if cmd[1:2] == ['install']:                       # npm install
            (cwd / 'node_modules' / '.bin').mkdir(parents=True)
        return 'ok'

    monkeypatch.setattr(sdk_deploy, '_execute', fake)
    out = sdk_deploy.run_scoped_flow({'record': {'name': 'Flow'}}, install=True, client=PrefixClient(),
                                     instance_url='https://dev410284.service-now.com', username='admin', password='pw')
    from app.config import get_settings
    get_settings.cache_clear()
    project = tmp_path / 'data' / 'sdk' / 'dev410284_service_now_com'
    config = json.loads((project / 'now.config.json').read_text())
    assert config['scope'] == 'x_1234567_nbuild' and len(config['scopeId']) == 32
    assert json.loads((project / 'package.json').read_text())['devDependencies']['@servicenow/sdk'] == '4.14.0'
    assert (project / 'src' / 'fluent' / 'nowbuilder_flow.now.ts').read_text().startswith('// Generated by nowBuilder')
    assert out['installed']
    npm = next(c for c in calls if c[0][1:2] == ['install'])
    assert npm[1] is not None and npm[1].name == 'setup_dev410284_service_now_com.log'   # watchable


def test_a_slow_setup_makes_the_flow_wait_instead_of_failing(tmp_path, monkeypatch):
    import threading
    _auto_mode(tmp_path, monkeypatch)
    monkeypatch.setenv('NOWBUILDER_SDK_WAIT_SECONDS', '0')
    release = threading.Event()

    def slow(cwd, cmd, timeout, env=None, stdin=None, log=None, live=False):
        if cmd[1:2] == ['install']:
            release.wait(5)                                 # npm still downloading
        return 'ok'

    monkeypatch.setattr(sdk_deploy, '_execute', slow)
    with pytest.raises(sdk_deploy.SDKSetupPending, match="click Deploy on the plan card"):
        sdk_deploy.run_scoped_flow({'record': {'name': 'Flow'}}, install=True, client=PrefixClient(),
                                   instance_url='https://dev410284.service-now.com', username='admin', password='pw')
    assert sdk_deploy.setup_state('https://dev410284.service-now.com')['state'] == 'running'
    release.set()
    from app.config import get_settings
    get_settings.cache_clear()


