def test_a_half_installed_sdk_is_repaired_before_it_is_called_ready(tmp_path, monkeypatch):
    """The real failure on 3 Nov: npm left node_modules without lodash, and `now-sdk auth` died with
    "Cannot find module 'lodash/noop'". The setup has to notice, add the package, and only then mark ready."""
    _auto_mode(tmp_path, monkeypatch)
    calls, state = [], {'lodash': False}

    def fake(cwd, cmd, timeout, env=None, stdin=None, log=None, live=False):
        calls.append(cmd)
        if cmd[1:2] == ['install']:
            (cwd / 'node_modules' / '.bin').mkdir(parents=True, exist_ok=True)
            if 'lodash' in cmd:
                state['lodash'] = True
        if cmd[-2:] == ['auth', '--list'] and not state['lodash']:
            raise sdk_deploy.SDKDeployError("`--no-install now-sdk auth` failed (exit 1): Error: Cannot find module "
                                            "'lodash/noop' Require stack: - ...sdk-build-core/dist/fs.js")
        return 'ok'

    monkeypatch.setattr(sdk_deploy, '_execute', fake)
    url = 'https://dev410284.service-now.com'
    sdk_deploy.ensure_project(url, 'admin', 'pw', PrefixClient())
    from app.config import get_settings
    get_settings.cache_clear()
    assert any(c[1:3] == ['install', 'lodash'] for c in calls)
    assert sdk_deploy.project_ready(url)
    package = json.loads((sdk_deploy.project_dir(url) / 'package.json').read_text())
    assert 'lodash' in package['devDependencies']            # pinned for next time too


